def B(v, n, quote):
    return (f'v{v:03d}-b{n:04d}', quote)

def N(v, n, note, quote, book):
    return (f'v{v:03d}-b{n:04d}-n{note:02d}', quote, book)

def T(title, text, *sources, eventLinks=None):
    r = dict(title=title, text=text, sources=list(sources))
    if eventLinks: r['eventLinks'] = [dict(label=a, eventId=b) for a,b in eventLinks]
    return r

def C(when, title, text, office, *sources, events=()):
    return dict(when=when, title=title, text=text, office=office, sources=list(sources), eventIds=list(events))

def D(when, title, category, text, *sources, events=()):
    return dict(when=when, title=title, category=category, text=text, sources=list(sources), eventIds=list(events))

def R(name, label, *sources):
    return dict(name=name, label=label, sources=list(sources))

